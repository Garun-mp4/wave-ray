import test from 'node:test';
import assert from 'node:assert/strict';
import vm from 'node:vm';
import { readFileSync } from 'node:fs';
import * as viewModel from './view-model.js';

const source = readFileSync(new URL('./app.js', import.meta.url), 'utf8')
  .replaceAll('\r\n', '\n')
  .replace(/^import[\s\S]*?from [^;]+;\n/gm, '')
  .replaceAll('import.meta.url', "'http://localhost:3000/ui/workspace/app.js'")
  .replace(/init\(\)\.catch\([\s\S]*$/, '');
function app() {
  const main = { querySelector: () => null, dataset: {}, innerHTML: '' };
  const sandbox = {
    ...viewModel, document: { getElementById: id => id === 'main' ? main : null },
    window: { location: { hash: '', origin: 'http://localhost:3000' } },
    localStorage: { getItem: () => null }, apiService: { setAuthToken() {} },
    API_TOKEN_STORAGE_KEY: 'token', SIM_FALLBACK_STORAGE_KEY: 'fallback', console,
  };
  vm.createContext(sandbox);
  vm.runInContext(source, sandbox);
  return { sandbox, main, run: code => vm.runInContext(code, sandbox) };
}
test('obsolete space route resolves to monitor and malformed routes are safe', () => {
  const a = app();
  for (const hash of ['#space', '#<script>', '#not-a-page', '']) {
    a.sandbox.window.location.hash = hash;
    assert.equal(a.run('parseRoute()'), 'overview');
  }
  a.sandbox.window.location.hash = '#calibration';
  assert.equal(a.run('parseRoute()'), 'calibration');
});
test('routes backed by global state do not enter a permanent loading state', async () => {
  const a = app();
  for (const route of ['overview', 'settings', 'help']) {
    await a.run(`loadRoute('${route}')`);
    assert.equal(a.run(`state.page['${route}']?.loading`), undefined);
  }
});
test('monitor keeps diagnostics optional and escapes source data', () => {
  const a = app();
  a.run("state.health = {source:'simulate',nodes:1}; state.latest = {source:'simulate',source_state:'synthetic',classification:{motion_level:'<script>bad</script>'}};");
  const html = a.run('renderOverview()');
  assert.match(html, /<details class="diagnostics">/);
  assert.match(html, /generated by the simulator/);
  assert.doesNotMatch(html, /<script>bad/);
  assert.match(html, /&lt;script&gt;/);
  assert.match(html, /href="#devices"/);
  assert.match(html, /href="#calibration"/);
  assert.match(html, /href="#recordings"/);
});
test('expired authorization takes precedence over a cached synthetic source', () => {
  const a = app();
  a.run("state.health = {source:'simulate'}; state.infoError = {status:401};");
  assert.equal(a.run('sourcePresentation().mode'), 'auth');
  assert.match(a.run('renderOverview()'), /href="#settings"/);
});
test('room calibration cannot be started from generated sensor input', () => {
  const a = app();
  a.run("state.health = {source:'simulate'}; state.page.devices = {nodes:[{node_id:1,status:'active',csi_status:'active'}]};");
  const html = a.run('renderCalibration({})');
  assert.match(html, /type="submit" disabled>Start baseline capture/);
  assert.match(html, /Connect a live raw CSI source/);
});
test('all calibration controls send the current server identity', async () => {
  for (const action of ['calibration-stop', 'calibration-cancel', 'calibration-reset']) {
    const a = app();
    a.sandbox.window.confirm = () => true;
    a.run("state.page.calibration = {status:{boot_epoch:'boot-2',session_id:'capture-3',binding_digest:'digest',source_node_ids:[2,4]}};");
    a.run('performAction = async (target, task) => task();');
    const calls = [];
    a.sandbox.api = { post: (path, body) => { calls.push({ path, body }); } };
    a.sandbox.target = { dataset: { action } };
    await a.run('handleAction(target)');
    assert.equal(calls.length, 1);
    assert.equal(calls[0].body.boot_epoch, 'boot-2');
    assert.equal(calls[0].body.session_id, 'capture-3');
    assert.equal(calls[0].path, '/api/v1/calibration/' + action.slice('calibration-'.length));
  }
});
test('calibration without an identity abstains instead of submitting a mutation', async () => {
  const a = app();
  a.run('showToast = () => {};');
  let called = false;
  a.sandbox.api = { post: () => { called = true; } };
  a.sandbox.target = { dataset: { action: 'calibration-stop' } };
  await a.run('handleAction(target)');
  assert.equal(called, false);
});
